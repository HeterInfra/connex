"""Minimal GRPO loop with an elastic vLLM rollout pool and instance churn.

Trainer: a Hugging Face causal LM on one GPU, trained with a GRPO-style
objective (group-normalised rewards, token-level policy gradient, no KL)
on synthetic addition problems (reward 1 if the answer is right).

Rollouts: ``RolloutPool`` over ``vllm serve`` engines (backend "connex") or,
with ``--engine sglang``, SGLang servers (custom weight loader).
After every optimizer step the trainer publishes the new weights and the
pool moves to the new version (drain, update, serve; ``--rolling k`` keeps
the rest serving). Churn: ``--kill STEP:PORT`` kills that engine in the
middle of the step's rollouts; ``--join STEP:GPU:PORT`` starts an engine
that catches up to the latest version before it serves.

Every rollout is generated by a single weight version (the pool's
invariant); the script records the version and instance of each rollout.

    python grpo_churn.py --model MODEL --engines 1:8101,3:8102 --steps 8 \\
        --kill 3:8102 --join 5:3:8103 --out grpo.jsonl
"""
import argparse
import asyncio
import json
import os
import random
import signal
import subprocess
import sys
import time

import torch

from connex.rl import RegistryServer, RolloutPool, WeightPublisher, WeightRegistry, make_transport
from connex.rl.engines import SGLangInstance, VLLMInstance
from connex.rl.transport import advertise_ip

HERE = os.path.dirname(os.path.abspath(__file__))


def start_engine(a, gpu, port):
    env = dict(os.environ, CUDA_VISIBLE_DEVICES=str(gpu), VLLM_SERVER_DEV_MODE="1",
               UCX_WARN_UNUSED_ENV_VARS="n")
    log = open(os.path.join(a.logdir, f"engine{port}.log"), "w")
    if a.engine == "sglang":
        cmd = [sys.executable, "-m", "sglang.launch_server", "--model-path", a.model,
               "--host", "127.0.0.1", "--port", str(port), "--mem-fraction-static", str(a.gmu),
               "--context-length", "2048", "--served-model-name", "policy",
               "--custom-weight-loader", "connex.rl.sglang_ext.connex_load"] + a.engine_args.split()
        return subprocess.Popen(cmd, env=env, stdout=log, stderr=subprocess.STDOUT,
                                start_new_session=True)
    cmd = [sys.executable, "-m", "vllm.entrypoints.cli.main", "serve", a.model, "--port", str(port),
           "--enforce-eager", "--gpu-memory-utilization", str(a.gmu), "--max-model-len", "2048",
           "--served-model-name", "policy", "--weight-transfer-config", '{"backend": "connex"}'
           ] + a.engine_args.split()
    return subprocess.Popen(cmd, env=env, stdout=log, stderr=subprocess.STDOUT,
                            start_new_session=True)


async def wait_up(port, proc, timeout=300):
    import aiohttp
    t0 = time.time()
    async with aiohttp.ClientSession(trust_env=False) as s:
        while time.time() - t0 < timeout:
            if proc.poll() is not None:
                raise RuntimeError(f"engine {port} exited")
            try:
                async with s.get(f"http://127.0.0.1:{port}/v1/models") as r:
                    if r.status == 200:
                        return time.time() - t0
            except Exception:
                pass
            await asyncio.sleep(1)
    raise TimeoutError(port)


def problems(rng, n, task):
    out = []
    for _ in range(n):
        x, y, z = rng.randint(10, 99), rng.randint(10, 99), rng.randint(10, 99)
        if task == "add":
            out.append((f"Compute {x} + {y}. Reply with the number only.\nAnswer:", str(x + y)))
        else:
            out.append((f"Compute {x} * {y} + {z}. Think step by step, then write the result "
                        f"as 'Final: <number>'.\n", str(x * y + z)))
    return out


def reward(text, ans):
    import re
    m = re.findall(r"Final:\s*(-?[\d,]+)", text)
    if m:
        return 1.0 if m[-1].replace(",", "") == ans else 0.0
    tok = text.strip().split()
    return 1.0 if tok and tok[0].strip(".,") == ans else 0.0


def logprobs(model, ids, n_prompt):
    out = model(ids.unsqueeze(0)).logits[0, :-1].float().log_softmax(-1)
    lp = out.gather(-1, ids[1:].unsqueeze(-1)).squeeze(-1)
    return lp[n_prompt - 1:]


async def main_async(a):
    from transformers import AutoModelForCausalLM, AutoTokenizer
    os.makedirs(a.logdir, exist_ok=True)
    rng = random.Random(0)
    tok = AutoTokenizer.from_pretrained(a.model)
    model = AutoModelForCausalLM.from_pretrained(a.model, dtype=torch.bfloat16).to(a.device)
    model.gradient_checkpointing_enable()
    model.train()
    opt = torch.optim.AdamW(model.parameters(), lr=a.lr)

    srv = RegistryServer(WeightRegistry(fanout=2), port=a.registry_port)
    reg_url = f"http://{advertise_ip()}:{srv.port}"
    pub = WeightPublisher(srv.reg, make_transport("connex-rs", lid=("grpo", 0, 0, 0)),
                          device=a.device)

    procs = {}
    pool = RolloutPool(version=0, drain_timeout=a.drain_timeout)

    async def join(gpu, port):
        t0 = time.time()
        procs[port] = start_engine(a, gpu, port)
        up = await wait_up(port, procs[port])
        cls = SGLangInstance if a.engine == "sglang" else VLLMInstance
        inst = cls(f"e{port}", f"http://127.0.0.1:{port}", "policy", reg_url, member=f"e{port}")
        await pool.add(inst)
        return {"event": "join", "port": port, "startup_s": round(up, 1),
                "join_to_serving_s": round(time.time() - t0, 1), "version": inst.version}

    def named():
        return [(n, p.detach()) for n, p in model.named_parameters()]

    v = pub.publish(named())             # version 1 = initial weights
    pool.version = v
    for spec in a.engines.split(","):
        g, p = spec.split(":")
        print(json.dumps(await join(int(g), int(p))), flush=True)

    kills = {int(s.split(":")[0]): int(s.split(":")[1]) for s in a.kill}
    joins = {int(s.split(":")[0]): (int(s.split(":")[1]), int(s.split(":")[2])) for s in a.join}
    outf = open(a.out, "a") if a.out else None
    for step in range(a.steps):
        probs = problems(rng, a.prompts, a.task)
        reqs = []
        for i, (q, ans) in enumerate(probs):
            ids = tok(q).input_ids
            for g in range(a.group):
                reqs.append({"prompt_ids": ids, "max_tokens": a.max_tokens, "temperature": 1.0,
                             "seed": step * 100000 + i * 100 + g, "ans": ans, "q": i})
        t0 = time.time()
        tasks = [asyncio.create_task(pool.generate(r)) for r in reqs]
        churn = []
        if step in kills:
            await asyncio.sleep(a.kill_after)
            port = kills[step]
            os.killpg(procs[port].pid, signal.SIGKILL)
            churn.append({"event": "kill", "port": port, "at_s": round(time.time() - t0, 2)})
        join_task = asyncio.create_task(join(*joins[step])) if step in joins else None
        res = await asyncio.gather(*tasks)
        t_roll = time.time() - t0
        # GRPO update
        texts = [tok.decode(r["tokens"], skip_special_tokens=True) for r in res]
        rewards = torch.tensor([reward(t, q["ans"]) for t, q in zip(texts, reqs)])
        rg = rewards.view(a.prompts, a.group)
        adv = ((rg - rg.mean(1, keepdim=True)) / (rg.std(1, keepdim=True) + 1e-4)).view(-1)
        t1 = time.time()
        opt.zero_grad()
        loss_sum = 0.0
        for r, q, A in zip(res, reqs, adv.tolist()):
            if A == 0 or not r["tokens"]:
                continue
            ids = torch.tensor(q["prompt_ids"] + r["tokens"], device=a.device)
            lp = logprobs(model, ids, len(q["prompt_ids"]))
            loss = -(A * lp.sum()) / (len(reqs) * a.max_tokens)
            loss.backward()
            loss_sum += float(loss)
        opt.step()
        t_train = time.time() - t1
        t2 = time.time()
        v = pub.publish(named())
        t_pub = time.time() - t2
        n_upd = await pool.update(v, rolling=a.rolling)
        t_upd = time.time() - t2
        if join_task is not None:
            churn.append(await join_task)
        rec = {"step": step, "reward": float(rewards.mean()), "loss": loss_sum,
               "rollouts": len(res), "rollout_tokens": sum(len(r["tokens"]) for r in res),
               "rollout_s": round(t_roll, 2),
               "goodput_tok_s": round(sum(len(r["tokens"]) for r in res) / t_roll, 1), "train_s": round(t_train, 2),
               "publish_s": round(t_pub, 3), "pool_update_s": round(t_upd, 2),
               "updated_instances": n_upd, "new_version": v,
               "versions_used": sorted({r["version"] for r in res}),
               "instances_used": sorted({r["instance"] for r in res}),
               "max_attempts": max(r["attempts"] for r in res),
               "pool": {k: v2 for k, v2 in pool.stats.items() if k != "updates"},
               "members": srv.reg.status()["members"], "churn": churn}
        print(json.dumps(rec), flush=True)
        if outf:
            outf.write(json.dumps(rec) + "\n")
            outf.flush()
    for sl in list(pool.slots.values()):
        await sl.inst.close()
    for p in procs.values():
        try:
            os.killpg(p.pid, signal.SIGTERM)
        except ProcessLookupError:
            pass
    for p in procs.values():
        try:
            p.wait(30)
        except subprocess.TimeoutExpired:
            os.killpg(p.pid, signal.SIGKILL)
    srv.close()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", required=True)
    ap.add_argument("--engines", required=True, help="gpu:port,...")
    ap.add_argument("--engine", choices=["vllm", "sglang"], default="vllm")
    ap.add_argument("--engine-args", default="", help="extra engine CLI arguments")
    ap.add_argument("--device", default="cuda:0")
    ap.add_argument("--steps", type=int, default=6)
    ap.add_argument("--prompts", type=int, default=8)
    ap.add_argument("--group", type=int, default=4)
    ap.add_argument("--max-tokens", type=int, default=16)
    ap.add_argument("--task", choices=["add", "reason"], default="add")
    ap.add_argument("--lr", type=float, default=1e-6)
    ap.add_argument("--gmu", type=float, default=0.25)
    ap.add_argument("--rolling", type=int, default=None)
    ap.add_argument("--drain-timeout", type=float, default=None)
    ap.add_argument("--kill", action="append", default=[], help="STEP:PORT")
    ap.add_argument("--kill-after", type=float, default=0.5)
    ap.add_argument("--join", action="append", default=[], help="STEP:GPU:PORT")
    ap.add_argument("--registry-port", type=int, default=29710)
    ap.add_argument("--logdir", default="grpo-logs")
    ap.add_argument("--out", default=None)
    asyncio.run(main_async(ap.parse_args()))


if __name__ == "__main__":
    main()
